"""R3 exact-equality tests: dates, time, decimals (Russian spoken norm)."""

from __future__ import annotations

import pytest

from minispeech.frontend.verbalize import verbalize_text


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        (
            "Дата 01.02.2020",
            "Дата первое февраля две тысячи двадцатого года",
        ),
        (
            "Платёж 12.05.2024",
            "Платёж двенадцатое мая две тысячи двадцать четвёртого года",
        ),
        (
            "Срок до 31.12.2026",
            "Срок до тридцать первого декабря две тысячи двадцать шестого года",
        ),
        (
            "с 01.01.2021",
            "с первого января две тысячи двадцать первого года",
        ),
        (
            "от 15.03.2019",
            "от пятнадцатого марта две тысячи девятнадцатого года",
        ),
        (
            "по 08.08.2022",
            "по восьмого августа две тысячи двадцать второго года",
        ),
        (
            "операция 23 июля 2026",
            "операция двадцать третье июля две тысячи двадцать шестого года",
        ),
    ],
)
def test_r3_dates_exact(raw: str, expected: str) -> None:
    assert verbalize_text(raw) == expected


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("Открытие в 09:05", "Открытие в девять ноль пять"),
        ("Оплата в 14:00", "Оплата в четырнадцать ноль ноль"),
        ("после 07:01", "после семь ноль один"),
        ("к 10:10", "к десять десять"),
        ("до 16:30", "до шестнадцати тридцати"),
        (
            "Приём с 09:05 до 18:30",
            "Приём с девяти ноль пяти до восемнадцати тридцати",
        ),
        ("от 08:00 до 12:00", "от восьми ноль ноль до двенадцати ноль ноль"),
    ],
)
def test_r3_time_exact(raw: str, expected: str) -> None:
    assert verbalize_text(raw) == expected


@pytest.mark.parametrize(
    ("raw", "expected"),
    [
        ("Коэффициент риска 0,25", "Коэффициент риска ноль целых двадцать пять сотых"),
        ("Ставка 2,5", "Ставка два целых пять десятых"),
        ("Индекс 1,5", "Индекс одна целая пять десятых"),
        ("Шаг 0,5", "Шаг ноль целых пять десятых"),
        ("Допуск 3,14", "Допуск три целых четырнадцать сотых"),
        ("Курс 10,05", "Курс десять целых пять сотых"),
        ("версия 2.5", "версия два точка пять"),
    ],
)
def test_r3_decimals_exact(raw: str, expected: str) -> None:
    assert verbalize_text(raw) == expected
