#!/usr/bin/env python3
"""List, inspect, verify, and document the audited corpus registry."""

from __future__ import annotations

import argparse
import json
import sys
from dataclasses import asdict
from pathlib import Path
from typing import Sequence

from minispeech.data.corpus_registry import get_corpus, iter_registered
from minispeech.data.manifest import iter_manifest
from minispeech.utils import expand, load_yaml

ROOT = Path(__file__).resolve().parents[1]


def _training_label(value: bool | None) -> str:
    if value is True:
        return "yes"
    if value is False:
        return "no"
    return "LEGAL REVIEW"


def render_markdown() -> str:
    lines = [
        "# Corpus registry",
        "",
        "<!-- Generated by scripts/55_corpus_registry.py docs. Do not edit by hand. -->",
        "",
        "| ID | Corpus | Hours | Speakers | License | Train | Gated | SR | Channel | Checked |",
        "|---|---|---:|---:|---|---|---|---:|---|---|",
    ]
    for info in iter_registered():
        lines.append(
            "| {id} | [{name}]({url}) | {hours} | {speakers} | {license} | "
            "{training} | {gated} | {sr} | {channel} | {checked} |".format(
                id=info.id,
                name=info.name.replace("|", "/"),
                url=info.source_url,
                hours="—" if info.hours is None else f"{info.hours:g}",
                speakers="—" if info.n_speakers is None else info.n_speakers,
                license=info.license.replace("|", "/"),
                training=_training_label(info.training_allowed),
                gated="yes" if info.gated else "no",
                sr="—" if info.default_sample_rate is None else info.default_sample_rate,
                channel=info.default_channel,
                checked=info.checked_at,
            )
        )
    lines.extend(["", "## Provenance notes", ""])
    for info in iter_registered():
        lines.extend(
            [
                f"### `{info.id}`",
                "",
                f"- Source: {info.source}",
                f"- URL: {info.source_url}",
                f"- License: {info.license}",
                f"- Training allowed: {_training_label(info.training_allowed)}",
                f"- Notes: {info.notes}",
                "",
            ]
        )
    lines.extend(
        [
            "Unknown facts are shown as `—`; they are not estimates. `LEGAL REVIEW`",
            "is a hard block, not an implied permission.",
            "",
        ]
    )
    return "\n".join(lines)


def _manifest_from_data_config(path: str) -> Path:
    cfg = load_yaml(path)
    if isinstance(cfg.get("data"), dict):
        value = cfg["data"].get("manifest")
    elif isinstance(cfg.get("ingest"), dict):
        value = cfg["ingest"].get("manifest")
    else:
        value = None
    if not value:
        raise ValueError(f"{path}: expected data.manifest or ingest.manifest")
    return expand(value)


def verify_manifest(data_config: str) -> dict[str, object]:
    manifest = _manifest_from_data_config(data_config)
    if not manifest.is_file():
        raise FileNotFoundError(f"manifest not found: {manifest}")
    counts: dict[str, int] = {}
    errors: list[str] = []
    n = 0
    for row in iter_manifest(manifest):
        n += 1
        corpus_id = row.corpus
        if not corpus_id:
            errors.append(f"{row.utt_id}: missing corpus")
            continue
        info = get_corpus(corpus_id)
        if info is None:
            errors.append(f"{row.utt_id}: unknown corpus {corpus_id!r}")
            continue
        if row.license != info.license:
            errors.append(
                f"{row.utt_id}: license {row.license!r} != registry {info.license!r}"
            )
        counts[corpus_id] = counts.get(corpus_id, 0) + 1
    return {
        "ok": not errors,
        "data_config": str(expand(data_config)),
        "manifest": str(manifest),
        "n": n,
        "corpora": dict(sorted(counts.items())),
        "errors": errors[:100],
        "n_errors": len(errors),
    }


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    sub.add_parser("list", help="Print a compact registry table")
    show = sub.add_parser("show", help="Print one registry record")
    show.add_argument("--corpus", required=True)
    verify = sub.add_parser("verify", help="Verify manifest provenance against registry")
    verify.add_argument("--data", required=True)
    docs = sub.add_parser("docs", help="Generate the Markdown registry")
    docs.add_argument("--out", default="docs/corpus_registry.md")
    return parser


def main(argv: Sequence[str] | None = None) -> int:
    args = _parser().parse_args(argv)
    try:
        if args.command == "list":
            print("id\thours\tspeakers\tlicense\ttrain\tgated\tchannel")
            for info in iter_registered():
                print(
                    f"{info.id}\t{info.hours}\t{info.n_speakers}\t{info.license}\t"
                    f"{_training_label(info.training_allowed)}\t{info.gated}\t"
                    f"{info.default_channel}"
                )
            return 0
        if args.command == "show":
            info = get_corpus(args.corpus)
            if info is None:
                raise ValueError(f"unknown corpus {args.corpus!r}")
            print(json.dumps(asdict(info), ensure_ascii=False, indent=2))
            return 0
        if args.command == "verify":
            result = verify_manifest(args.data)
            print(json.dumps(result, ensure_ascii=False, indent=2))
            return 0 if result["ok"] else 1

        output = expand(args.out)
        output.parent.mkdir(parents=True, exist_ok=True)
        output.write_text(render_markdown(), encoding="utf-8", newline="\n")
        print(output)
        return 0
    except (FileNotFoundError, ValueError) as exc:
        print(f"ERROR: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
